"""The open questions of an issue or a spec PR, read from its body (S-1.75).

One reader for every place that needs them: the open-questions gate, the orchestrator's
spec stages (`sprint_proposals.py`), and screens that show the questions, such as
dolev-hub's sprint screen. The gate runs with nothing but `python3` and `gh`, so this
module imports no other module of the pipeline.

What counts as an open question
-------------------------------
The `## שאלות פתוחות` (or `Open questions`) section of the body is the single source of
truth. Inside it:

    - [ ] question           -> open
    - [x] question - הוחלט:  -> resolved, kept for the record

An open box with indented lines under it (its options, say) is one question, returned
with those lines.

A section that contains **no checkbox at all** pre-dates the convention. There, every
non-empty line counts as an open question, bullet or prose alike. That is deliberately
generous: a false warning costs a glance, a missed question costs a wrong merge, and the
way to make it precise is to add the checkboxes. One checkbox anywhere in the section
switches it to the exact rule. Four kinds of line are skipped even there:
a placeholder in italics (one `_` or `*` on each side; a bold line is a question,
claude-config #153), a horizontal rule, an HTML comment - so the "---" and
"_Generated by Claude Code_" footer a cloud session appends to every body is not a
question (claude-config #142) - and a line that only says there are none ("אין.",
claude-config #523).

Questions asked in comments do not count - the Plan phase copies them into the section,
so this stays one parse of one place.

When they block
---------------
By the issue's status, not by a mark on the question: an issue in
`status:plan-questions` waits for Dolev's answer, so its questions block it. A question
in any other status is open, and only the gate before the merge stops on it.
"""

import re

SECTION_TITLES = ("שאלות פתוחות", "open questions")
BLOCKING_STATUS = "status:plan-questions"

HEADING_RE = re.compile(r"^\s{0,3}(#{1,6})\s*(.+?)\s*#*\s*$")
UNCHECKED_RE = re.compile(r"^\s*[-*+]\s*\[\s\]\s*(.+?)\s*$")
CHECKED_RE = re.compile(r"^\s*[-*+]\s*\[[xX]\]\s*")
BULLET_RE = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s+(.+?)\s*$")
# "_טרם נכתבה תוכנית._" and friends - a template placeholder, not a question. It also
# covers the "_Generated by [Claude Code](...)_" footer a cloud session appends.
# Only a single `_` or `*` on each side: "**מה המטבע?**" is a bold question (#153).
PLACEHOLDER_RE = re.compile(r"^\s*(?:_(?!_).*(?<!_)_|\*(?!\*).*(?<!\*)\*)\s*$")
# A Markdown horizontal rule. A cloud session appends "---" before its footer, which
# lands in this section, the last one in the body (claude-config #142).
RULE_RE = re.compile(r"^\s{0,3}([-*_])(?:\s*\1){2,}\s*$")
# The section is the last one in the body, so the hidden sync marker falls inside it.
COMMENT_RE = re.compile(r"^\s*<!--.*-->\s*$")
# A line that only says there are no questions (#523: "אין." was read as one).
NONE_WORDS = {"אין", "אין שאלות", "אין שאלות פתוחות", "none"}


def find_section(body: str | None) -> tuple[str, list[str]] | None:
    """(heading, lines) of the open-questions section, or None without such a section.

    The heading comes back as written, so a warning names the section the way the repo
    spells it (business-plan-generator writes "Open questions").

    A plan may carry its own "open questions" subsection, which comes before the issue's
    section - so the first match is the wrong one (Osea #1, 24.10.2026). The issue's
    section is always the last one, both in bodies written with `##` and in issue-form
    bodies, where every field is `###`. It ends at the next heading of the same or a
    higher level.
    """
    lines = (body or "").splitlines()
    headings = [
        (i, len(m.group(1)), m.group(2).strip())
        for i, m in ((i, HEADING_RE.match(line)) for i, line in enumerate(lines))
        if m
    ]
    matches = [
        (i, level, title)
        for i, level, title in headings
        if any(t in title.lower() for t in SECTION_TITLES)
    ]
    if not matches:
        return None
    start, level, title = matches[-1]
    end = next((i for i, lv, _ in headings if i > start and lv <= level), len(lines))
    return title, lines[start + 1 : end]


def says_none(line: str) -> bool:
    """True for a line whose whole text says there are no questions ("אין.")."""
    m = BULLET_RE.match(line)
    text = (m.group(1) if m else line).strip().strip("*_").strip().rstrip(".").strip()
    return text.lower() in NONE_WORDS


def is_skipped(line: str) -> bool:
    """A line that is never a question: blank, answered, placeholder, rule, comment."""
    return (
        not line.strip()
        or bool(CHECKED_RE.match(line))
        or bool(PLACEHOLDER_RE.match(line))
        or bool(RULE_RE.match(line))
        or bool(COMMENT_RE.match(line))
    )


def open_questions(body: str | None, boxes_only: bool = False) -> list[str]:
    """The open questions in the body's open-questions section; empty when none.

    Each question is its text; an open box with indented lines under it comes back as
    one string, those lines joined to it with newlines.

    `boxes_only` reads every section by the exact rule, never the lenient one: a spec
    PR's body always writes its questions as boxes (`reference/specs.md`), and its last
    section runs into the `Refs #N` line and the footer, which are not questions.
    """
    section = find_section(body)
    if section is None:
        return []
    lines = section[1]
    structured = boxes_only or any(
        UNCHECKED_RE.match(line) or CHECKED_RE.match(line) for line in lines
    )
    found: list[str] = []
    in_open_box = False
    for line in lines:
        m = UNCHECKED_RE.match(line)
        if m:
            found.append(m.group(1))
            in_open_box = True
            continue
        if structured and in_open_box and line[:1].isspace() and not is_skipped(line):
            found[-1] += "\n" + line.rstrip()
            continue
        in_open_box = False
        if structured or is_skipped(line) or says_none(line):
            continue
        # Legacy section - no checkbox to key on, so take the line as it stands.
        m = BULLET_RE.match(line)
        found.append(m.group(1) if m else line.strip())
    return found


def is_blocking(labels: list[str]) -> bool:
    """True when the issue's questions block it: it waits for Dolev's answer."""
    return BLOCKING_STATUS in labels
